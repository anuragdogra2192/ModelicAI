import json
import os
from langchain_anthropic import ChatAnthropic
from langchain_core.messages import HumanMessage, SystemMessage
import plotly.graph_objects as go
from plotly.subplots import make_subplots
import scipy.io as sio
import numpy as np


class VisualizationAgent:

  def __init__(self):
    self.llm = ChatAnthropic(
        model=os.getenv("MODEL_NAME", "claude-haiku-5-5")
    )

  def design_dashboard_layout(
      self, available_variables: list, user_intent: str
  ) -> dict:
    """Uses the LLM to inspect available variables and user intent,

    then designs an optimal interactive dashboard layout in JSON.
    """
    system_prompt = (
        "You are an expert CAE data visualization engineer. "
        "Given the available simulation variables and user intent, design an interactive dashboard layout. "
        "Return ONLY a valid JSON object with this structure:\n"
        "{\n"
        '  "title": "Dashboard Title",\n'
        '  "subplots": [\n'
        "    {\n"
        '      "variable": "vC",\n'
        '      "title": "Capacitor Voltage",\n'
        '      "y_axis_label": "Voltage (V)",\n'
        '      "color": "blue"\n'
        "    }\n"
        "  ]\n"
        "}"
    )

    user_content = (
        f"Available Variables in Result File: {available_variables}\n"
        f"User Visualization Goal: {user_intent}"
    )

    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=user_content),
    ]
    response = self.llm.invoke(messages)

    content = response.content
    if isinstance(content, list):
      content_str = "".join(
          [
              block.get("text", "") if isinstance(block, dict) else str(block)
              for block in content
          ]
      )
    else:
      content_str = str(content)

    if "```json" in content_str:
      content_str = content_str.split("```json")[1].split("```")[0].strip()
    elif "```" in content_str:
      content_str = content_str.split("```")[1].split("```")[0].strip()

    try:
      return json.loads(content_str)
    except json.JSONDecodeError:
      return {
          "title": "Simulation Results Dashboard",
          "subplots": [{
              "variable": available_variables[0] if available_variables else "vC",
              "title": "Simulation Variable",
              "y_axis_label": "Value",
              "color": "blue",
          }],
      }

  def render_dashboard(
      self, omc_session, result_file: str, user_intent: str, output_dir: str = "."
  ) -> str:
    """Agent tool: Directly parses .mat result file with SciPy,

    consults LLM for layout, and renders an interactive Plotly HTML dashboard.
    """
    print(
        f"[VisualizationAgent] Inspecting result file via direct .mat parsing:"
        f" {result_file}"
    )

    if not os.path.exists(result_file):
      raise FileNotFoundError(f"Simulation result file not found: {result_file}")

    # Load MATLAB .mat container generated by OpenModelica
    mat_data = sio.loadmat(result_file)

    # Extract available variable names (filter out metadata fields starting with '__')
    available_vars = [
        k for k in mat_data.keys() if not k.startswith("__")
    ]

    print(
        "[VisualizationAgent] Designing layout using LLM based on user intent..."
    )
    layout_config = self.design_dashboard_layout(available_vars, user_intent)
    print(json.dumps(layout_config, indent=2))

    # Extract time series array
    time_key = "time" if "time" in mat_data else available_vars[0]
    time = mat_data[time_key].flatten() if time_key in mat_data else np.array([])

    subplots = layout_config.get("subplots", [])

    fig = make_subplots(
        rows=len(subplots),
        cols=1,
        shared_xaxes=True,
        subplot_titles=[sub["title"] for sub in subplots],
    )

    for idx, sub in enumerate(subplots, start=1):
      var_name = sub["variable"]
      
      # Handle matching variables in mat_data safely
      if var_name in mat_data:
        y_data = mat_data[var_name].flatten()
      else:
        # Fallback search if exact name casing differs slightly
        match = next((k for k in available_vars if k.lower() == var_name.lower()), None)
        y_data = mat_data[match].flatten() if match else np.zeros_like(time)

      if len(y_data) > 0:
        fig.add_trace(
            go.Scatter(
                x=time,
                y=y_data,
                mode="lines",
                name=var_name,
                line=dict(color=sub.get("color", "blue"), width=2),
            ),
            row=idx,
            col=1,
        )

    fig.update_layout(
        title_text=f"<b>{layout_config.get('title', 'Simulation Dashboard')}</b>",
        xaxis_title="Time (s)",
        template="plotly_white",
        height=350 * len(subplots),
    )

    output_html = os.path.join(output_dir, "interactive_dashboard.html")
    fig.write_html(output_html)
    print(
        f"\n✨ [VisualizationAgent] Interactive dashboard generated:"
        f" {output_html}"
    )
    return output_html